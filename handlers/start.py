"""
Обработчики для базовых команд: /start и /help
"""

from aiogram import Router
from aiogram.filters import Command, CommandStart
from aiogram.types import Message
from aiogram import html

# Создаем роутер для базовых команд
router = Router(name="start")


@router.message(CommandStart())
async def command_start_handler(message: Message) -> None:
    """
    Обработчик команды /start
    Отправляет приветственное сообщение пользователю
    """
    user_name = message.from_user.full_name
    welcome_text = f"""
👋 <b>Привет, {html.quote(user_name)}!</b>

Я <b>AI-консультант</b>, созданный для того, чтобы помогать вам с вопросами и задачами.

Я использую передовые AI-модели для:
• Ответов на вопросы
• Помощи в решении задач
• Поддержки естественного диалога
• Запоминания контекста беседы

<b>📋 Доступные команды:</b>
/start - Показать это приветствие
/help - Получить подробную справку
/ask [вопрос] - Задать вопрос AI
/clear - Очистить историю диалога
/stats - Статистика диалога
/context - Управление размером контекста
/settings - Настройки бота

<b>💡 Как использовать:</b>
Просто напишите мне сообщение, и я отвечу!
Или используйте команду <code>/ask</code> для конкретного вопроса.

Давайте начнем! 🚀
"""
    await message.answer(welcome_text)


@router.message(Command("help"))
async def command_help_handler(message: Message) -> None:
    """
    Обработчик команды /help
    Показывает подробную справку по использованию бота
    """
    help_text = """
📖 <b>Справка по использованию AI-консультанта</b>

<b>🎯 Основные команды:</b>

<b>/start</b> - Начать работу с ботом
└ Показывает приветственное сообщение

<b>/help</b> - Справка
└ Показывает это сообщение с подробной информацией

<b>/ask [вопрос]</b> - Задать вопрос AI
└ Пример: <code>/ask Что такое Python?</code>
└ Или просто напишите сообщение без команды

<b>/clear</b> - Очистить историю
└ Удаляет историю диалога и начинает новую беседу
└ Полезно для смены темы разговора

<b>/stats</b> - Статистика диалога
└ Показывает подробную статистику ваших сообщений
└ Информация о количестве сообщений и токенов

<b>/context [число]</b> - Управление контекстом
└ Изменить количество запоминаемых сообщений
└ Пример: <code>/context 20</code> - запоминать 20 сообщений

<b>/settings</b> - Настройки
└ Просмотр текущих настроек бота

<b>💬 Режимы работы:</b>

<b>1. Прямой диалог</b>
Просто отправьте сообщение, и бот ответит с учетом контекста беседы.

<b>2. Команда /ask</b>
Используйте для конкретных вопросов:
<code>/ask Объясни квантовую физику простыми словами</code>

<b>🔧 Возможности:</b>

✅ Естественный диалог на русском языке
✅ Запоминание контекста (настраиваемое)
✅ Ответы на вопросы любой сложности
✅ Помощь с программированием
✅ Объяснение сложных концепций
✅ Генерация идей и советов
✅ Сохранение истории диалогов в базе данных

<b>⚠️ Ограничения:</b>

• Лимит: 5 сообщений в минуту
• Контекст: настраивается через /context (по умолчанию 10)
• Бот не может получать доступ к интернету в реальном времени
• Информация актуальна на январь 2025

<b>📝 Примеры использования:</b>

1. <code>/ask Как работает искусственный интеллект?</code>
2. <code>/ask Напиши код на Python для сортировки списка</code>
3. Просто: <i>"Помоги мне решить математическую задачу"</i>
4. <code>/clear</code> - когда нужно начать новую тему

<b>❓ Возникли проблемы?</b>
Если бот не отвечает:
• Проверьте, не превысили ли вы лимит (5 сообщений/минуту)
• Попробуйте команду /clear для сброса контекста
• Используйте /start для перезапуска

<b>Готов помочь! Задайте мне вопрос или начните диалог 💬</b>
"""
    await message.answer(help_text)


@router.message(Command("settings"))
async def command_settings_handler(message: Message) -> None:
    """
    Обработчик команды /settings
    Показывает текущие настройки бота
    """
    settings_text = """
⚙️ <b>Настройки бота</b>

<b>🤖 AI Модель:</b>
• Используется: <code>llama-3.3-70b-versatile</code>
• Провайдер: Groq API
• Температура: 0.7

<b>💬 Контекст диалога:</b>
• Запоминается: последние 5 сообщений
• Очистка: команда /clear

<b>⏱ Ограничения:</b>
• Лимит: 5 сообщений в минуту
• Максимум токенов: 1024

<b>📊 Ваша статистика:</b>
• User ID: <code>{user_id}</code>
• Имя: {full_name}

<i>Настройки применяются глобально для всех пользователей.</i>
"""
    await message.answer(
        settings_text.format(
            user_id=message.from_user.id,
            full_name=html.quote(message.from_user.full_name)
        )
    )
